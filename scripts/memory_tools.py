#!/usr/bin/env python3
"""Repository-local deterministic index and read-only memory review. Standard library only."""
import argparse
import datetime as dt
import json
from pathlib import Path
import re
import sys
from urllib.parse import unquote

import brain
import git_guard
import project_registry as registry
import session_sync

ROOT = Path(__file__).resolve().parents[1]
GENERATED = '<!-- Generated by scripts/memory_tools.py index; DO NOT EDIT. -->'
FOLDERS = (*brain.CONTENT, 'sessions', 'inbox', 'archive', 'system', 'exports', 'automation')
CLOSED = {'종료', '해결됨', '안 고치기로 함', 'closed', 'resolved', 'archived'}
CONFLICT = re.compile(r'충돌|모순|상충|contested|conflict', re.I)
LINK = re.compile(r'(?<!!)\[[^\]]*\]\(([^\s)]+)(?:\s+"[^"]*")?\)')


def meta(text):
    front = text[4:].split('\n---\n', 1)[0] if text.startswith('---\n') else ''
    result = {}
    for line in front.splitlines():
        if ':' not in line or line.startswith((' ', '\t')):
            continue
        key, value = line.split(':', 1)
        value = value.strip()
        try:
            value = json.loads(value)
        except (ValueError, TypeError):
            value = value.strip("'\"")
        result[key] = value
    return result


def date(value):
    try:
        return dt.date.fromisoformat(str(value))
    except ValueError:
        return None


def link(path, label=None):
    label = str(label or path).replace('[', '(').replace(']', ')').replace('|', '\\|').replace('\n', ' ')
    return '[' + label + '](' + str(path).replace(' ', '%20') + ')'


def collect(root):
    """Never follow symlinks or inspect another checkout. No locks/cache writes."""
    root = root.resolve()
    docs = {}
    for path in brain.safe_files(root, FOLDERS):
        docs[path.relative_to(root).as_posix()] = path.read_text(encoding='utf-8')
    for name in ('README.md', 'AGENTS.md', 'CLAUDE.md', 'GEMINI.md', 'MEMORY.md'):
        path = session_sync.safe(root, name)
        if path.exists():
            docs[name] = path.read_text(encoding='utf-8')
    catalog, _ = registry.load(root)
    projects = []
    for entry in sorted(catalog['projects'], key=lambda e: e['id']):
        state = session_sync.snapshot_unlocked(root, entry['id'])
        projects.append((entry, state))
    return docs, projects


def is_open(path, data):
    return path.split('/')[0] in ('incidents', 'findings') and not path.endswith('/README.md') and data.get('status') != 'archived' and data.get('state') not in CLOSED


def conflict_paths(docs):
    # A keyword is only a review lead, never proof that a contradiction exists.
    return sorted(p for p, t in docs.items() if p.split('/')[0] in (*brain.CONTENT, 'sessions', 'inbox') and CONFLICT.search(t))


def render_index(root):
    docs, projects = collect(root)
    lines = [GENERATED, '# 기록 색인', '', '이 저장소만 포함합니다. 전체 파일을 재생성하며 수동 영역은 없습니다.',
             '미통합은 등록된 세션 그룹과 상위 정본의 integrated_sessions 기준입니다. 다른 worktree는 포함하지 않습니다.', '',
             '## 프로젝트', '', '| 프로젝트 | as_of | 등록 세션 그룹 | 미통합 |', '|---|---|---|---|']
    for entry, state in projects:
        path = 'projects/' + entry['id'] + '.md'
        label = link(path, entry['title']) if path in docs else entry['title'] + ' (정본 없음)'
        groups = ', '.join(state['groups'])
        lines.append('| ' + ' | '.join((label, str(meta(state['markdown']).get('as_of', '미확인')), groups, str(len(state['pending'])))) + ' |')
    lines += ['', '## 세션 그룹별 미통합', '']
    for entry, state in projects:
        for group in state['groups']:
            pending = [e for e in state['pending'] if e['project'] == group]
            lines.append('- ' + group + ': ' + str(len(pending)) + '건')
            for event in pending:
                lines.append('  - ' + link(event['path']) + ' · observed=' + event['observed'])
    lines += ['', '## 열린 incident·finding', '']
    opened = [p for p in sorted(docs) if is_open(p, meta(docs[p]))]
    for path in opened:
        data = meta(docs[path])
        lines.append('- ' + link(path) + ' · ' + str(data.get('state', '상태 미확인')) + ' · ' + str(data.get('priority', data.get('severity', '미확인'))))
    if not opened:
        lines.append('없음')
    lines += ['', '## 미해결 충돌 검토 후보', '', '키워드가 있는 문서 위치입니다. 해소 여부와 의미는 원문을 읽고 판단합니다.', '']
    candidates = conflict_paths(docs)
    lines.extend('- ' + link(p) for p in candidates)
    if not candidates:
        lines.append('없음')
    lines += ['', '## 최근 갱신 문서', '']
    recent = sorted(((str(meta(t).get('updated', '')), p) for p, t in docs.items() if date(meta(t).get('updated'))), key=lambda x: (x[0], x[1]), reverse=True)[:20]
    lines.extend('- ' + stamp + ' · ' + link(p) for stamp, p in recent)
    lines += ['', '## 전체 문서', '', '보관 문서도 경로만 표시합니다. 본문·출처는 복제하지 않습니다.', '']
    lines.extend('- ' + link(p) for p in sorted(docs))
    return '\n'.join(lines) + '\n'


def audit(root, as_of, stale_days=30, pending_days=14):
    docs, projects = collect(root)
    findings = []
    def add(kind, path, reason):
        findings.append({'kind': kind, 'path': path, 'reason': reason})
    def old(value, days):
        stamp = date(value)
        return stamp is not None and (as_of - stamp).days >= days
    registered_groups = set()
    for entry, state in projects:
        path = 'projects/' + entry['id'] + '.md'
        registered_groups.update(state['groups'])
        data = meta(state['markdown'])
        if not state['markdown']:
            add('missing-project', 'system/project-registry.json', entry['id'] + ': 정본 없음')
        elif not date(data.get('as_of')) or old(data.get('as_of'), stale_days):
            add('stale-project', path, 'as_of=' + str(data.get('as_of', '없음')))
        for event in state['pending']:
            # updated is the recording date; unknown/month-only observed never becomes a fabricated date.
            updated = meta(docs[event['path']]).get('updated')
            if old(updated, pending_days):
                add('old-pending', event['path'], '저장일=' + str(updated) + '; observed=' + event['observed'])
    incoming = set()
    for path, text in docs.items():
        for raw in LINK.findall(text):
            target = unquote(raw.split('#', 1)[0])
            if not target or re.match(r'^[A-Za-z][\w+.-]*:', target) or target.startswith('/'):
                continue
            resolved = (root / path).parent / target
            if root.resolve() not in resolved.resolve().parents:
                continue
            relative = resolved.resolve().relative_to(root.resolve()).as_posix()
            if relative != path:
                incoming.add(relative)
            # Only report; do not dereference or repair linked targets.
            if relative not in docs and relative not in ('INDEX.md',) and not resolved.exists():
                add('broken-link', path, target)
    for path, text in sorted(docs.items()):
        data = meta(text)
        folder = path.split('/')[0]
        if folder not in (*brain.CONTENT, 'sessions', 'inbox', 'archive') or path.endswith('/README.md'):
            continue
        if not data.get('source') or data.get('source') in ('미확인', 'unknown'):
            add('missing-source', path, '출처 없음 또는 미확인')
        if folder == 'sessions' and path.split('/')[1] not in registered_groups:
            add('unregistered-session', path, '등록된 세션 그룹이 아님')
        if path not in incoming and folder != 'sessions':
            add('orphan-candidate', path, 'INDEX 자동 링크를 제외한 유입 링크 없음; 독립 문서일 수 있음')
        if data.get('status') == 'draft' and old(data.get('updated'), stale_days):
            add('old-draft', path, 'updated=' + str(data.get('updated')))
        if is_open(path, data) and old(data.get('updated'), stale_days):
            add('old-open-item', path, '상태=' + str(data.get('state', '미확인')) + '; updated=' + str(data.get('updated')))
        blockers = re.search(r'^## Blockers\s*\n(.*?)(?=^## |\Z)', text, re.M | re.S)
        if blockers and old(data.get('as_of'), stale_days) and blockers.group(1).strip() not in ('', '없음', '- 없음', '없음.'):
            add('old-blocker-candidate', path, '오래된 Blockers 절; 실제 미해결 여부 검토 필요')
    for path in conflict_paths(docs):
        add('conflict-candidate', path, '충돌 관련 키워드; 의미 충돌 및 해소 여부는 미판정')
    index = session_sync.safe(root, 'INDEX.md')
    if not index.exists() or index.read_text(encoding='utf-8') != render_index(root):
        add('index-drift', 'INDEX.md', '없음 또는 재생성 결과와 불일치')
    return sorted(findings, key=lambda item: (item['kind'], item['path'], item['reason']))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest='command', required=True)
    idx = sub.add_parser('index')
    idx.add_argument('--check', action='store_true', help='Read-only exact regeneration comparison')
    rev = sub.add_parser('audit')
    rev.add_argument('--as-of', type=dt.date.fromisoformat, default=dt.date.fromisoformat(brain.today()))
    rev.add_argument('--stale-days', type=int, default=30)
    rev.add_argument('--pending-days', type=int, default=14)
    rev.add_argument('--json', action='store_true')
    args = parser.parse_args()
    try:
        if args.command == 'index':
            output = render_index(ROOT)
            path = session_sync.safe(ROOT, 'INDEX.md')
            if args.check:
                matches = path.exists() and path.read_text(encoding='utf-8') == output
                print('PASS' if matches else 'INDEX.md needs regeneration')
                return 0 if matches else 1
            git_guard.require_isolated(ROOT)
            if path.exists() and not path.read_text(encoding='utf-8').startswith(GENERATED + '\n'):
                raise ValueError('INDEX.md is not a managed generated file; review before replacement')
            session_sync.atomic(path, output)
            print('INDEX.md generated')
        else:
            if min(args.stale_days, args.pending_days) < 1:
                raise ValueError('day thresholds must be positive')
            result = audit(ROOT, args.as_of, args.stale_days, args.pending_days)
            if args.json:
                print(json.dumps({'as_of': str(args.as_of), 'findings': result}, ensure_ascii=False, indent=2))
            else:
                print('# 기억 점검 · ' + str(args.as_of) + '\n\n읽기 전용 후보 보고입니다. 사실 판정·통합·삭제·archive·개인 전달을 수행하지 않습니다.\n')
                for item in result:
                    print('- ' + item['kind'] + ' · ' + item['path'] + ' · ' + item['reason'])
                print('\n' + str(len(result)) + '건 (후보 중복 가능)')
    except (OSError, ValueError, KeyError, TypeError) as exc:
        print('ERROR: ' + str(exc), file=sys.stderr)
        return 2
    return 0


if __name__ == '__main__':
    sys.exit(main())
